const {chooseRetailReference:choose}=require('../dist/profit.js');
const sc={name:'SCG',price:150,stock:'in_stock'},ck={name:'CK',price:180,stock:'in_stock'};
assert.equal(choose([sc,ck]).name,'CK');
assert.equal(choose([{...sc,price:200},ck]).name,'SCG');
assert.equal(choose([{...sc,price:250,stock:'out_of_stock'},ck]).name,'CK');
assert.equal(choose([{...sc,stock:'out_of_stock'},{...ck,stock:'out_of_stock'}]),null);
assert.equal(choose([{...sc,stock:'unknown'},{...ck,price:NaN}]),null);
assert.equal(choose([{...sc,price:180},ck]).name,'SCG');
